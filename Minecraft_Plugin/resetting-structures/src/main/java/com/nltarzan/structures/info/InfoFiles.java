package com.nltarzan.structures.info;

import com.nltarzan.structures.ResettingStructures;
import com.nltarzan.structures.StructureModule;
import org.bukkit.plugin.java.JavaPlugin;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;
import java.util.logging.Level;

/**
 * Writes two read-only files to the plugin folder: status.txt (every structure's current status,
 * rewritten whenever it changes) and commands.txt (every command, grouped per structure, rewritten
 * on every start). They're marked read-only so an editor warns before saving over them; the plugin
 * lifts that just before rewriting them.
 */
public final class InfoFiles {

    public static final String STATUS_FILE = "status.txt";
    public static final String COMMANDS_FILE = "commands.txt";

    private static final int WIDTH = 90;
    private static final DateTimeFormatter TIME = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    /** One structure's section in status.txt. */
    public record StatusSection(String name, List<StatusLine> lines) {
    }

    /** One structure's group in commands.txt. */
    public record CommandGroup(String name, String commandName, List<CommandHelp> commands) {
    }

    private final JavaPlugin plugin;
    private final List<StructureModule> modules = new ArrayList<>();

    public InfoFiles(JavaPlugin plugin) {
        this.plugin = plugin;
    }

    public void add(StructureModule module) {
        modules.add(module);
    }

    public void writeStatus() {
        List<StatusSection> sections = modules.stream().map(m -> new StatusSection(m.name(), m.status())).toList();
        write(STATUS_FILE, statusText(sections, LocalDateTime.now()));
    }

    public void writeCommands() {
        List<CommandGroup> groups = modules.stream()
                .map(m -> new CommandGroup(m.name(), m.commandName(), m.commandHelp())).toList();
        write(COMMANDS_FILE, commandsText(groups));
    }

    /** The text of status.txt. */
    public static String statusText(List<StatusSection> sections, LocalDateTime updated) {
        StringBuilder out = new StringBuilder();
        header(out, "ResettingStructures - status",
                "Updated " + TIME.format(updated) + ". Rewritten by the plugin whenever something changes.");
        for (StatusSection section : sections) {
            out.append('\n').append(section.name()).append('\n');
            int labelWidth = section.lines().stream().mapToInt(l -> l.label().length()).max().orElse(0) + 2;
            for (StatusLine line : section.lines()) {
                out.append("  ").append(pad(line.label() + ":", labelWidth)).append(line.value()).append('\n');
            }
        }
        return out.toString();
    }

    /** The text of commands.txt. */
    public static String commandsText(List<CommandGroup> groups) {
        StringBuilder out = new StringBuilder();
        header(out, "ResettingStructures - commands",
                "Rewritten by the plugin on every start, so it always matches the installed version.");
        out.append('\n')
                .append("Every command needs the ").append(ResettingStructures.ADMIN_PERMISSION).append(" permission.\n")
                .append("How to read them:  <value> = required   [value] = optional   a|b = one of these\n")
                .append('\n')
                .append("/structure\n");
        wrap(out, "Lists the structures this plugin manages. Every structure has its own commands, below.", "    ");

        for (CommandGroup group : groups) {
            out.append('\n').append("-".repeat(WIDTH)).append('\n')
                    .append(group.name()).append("   (/structure ").append(group.commandName()).append(" ...)\n")
                    .append("-".repeat(WIDTH)).append('\n');
            for (CommandHelp command : group.commands()) {
                out.append('\n').append(command.usage()).append('\n');
                wrap(out, command.description(), "    ");
                for (String example : command.examples()) {
                    out.append("    Example: ").append(example).append('\n');
                }
            }
        }
        return out.toString();
    }

    private static void header(StringBuilder out, String title, String note) {
        out.append("=".repeat(WIDTH)).append('\n')
                .append(title).append('\n')
                .append("READ-ONLY: generated by the plugin, any changes you make to this file are lost.").append('\n')
                .append(note).append('\n')
                .append("=".repeat(WIDTH)).append('\n');
    }

    /** Word-wraps a text to the file width, every line starting with the indent. */
    private static void wrap(StringBuilder out, String text, String indent) {
        StringBuilder line = new StringBuilder(indent);
        for (String word : text.split(" ")) {
            if (line.length() > indent.length() && line.length() + 1 + word.length() > WIDTH) {
                out.append(line).append('\n');
                line = new StringBuilder(indent);
            }
            if (line.length() > indent.length()) {
                line.append(' ');
            }
            line.append(word);
        }
        out.append(line).append('\n');
    }

    private static String pad(String text, int width) {
        return text.length() >= width ? text + " " : text + " ".repeat(width - text.length());
    }

    private void write(String name, String text) {
        File file = new File(plugin.getDataFolder(), name);
        try {
            if (file.exists()) {
                file.setWritable(true);
            }
            Files.writeString(file.toPath(), text, StandardCharsets.UTF_8);
            file.setReadOnly();
        } catch (IOException e) {
            plugin.getLogger().log(Level.WARNING, "Could not write " + name, e);
        }
    }
}
